"""Replaces the upstream mc-safe-resources Gradle code generator."""
from pathlib import Path
import json
import re
root=Path(__file__).resolve().parents[1]
dest=root/'src/main/java/dev/war/openfight/generated'
dest.mkdir(exist_ok=True)
for cls,file in [('LangKeys','lang/en_us.json'),('SoundKeys','sounds.json')]:
    data=json.loads((root/'src/main/resources/assets/epicfight'/file).read_text(encoding='utf-8'))
    constants={}
    for key in data:
        parts=[p for p in re.split(r'[.\-/:]',key) if p!='epicfight']
        name='_'.join(parts).upper()
        if not re.fullmatch(r'[A-Z_][A-Z_0-9]*',name): raise ValueError(key)
        if name in constants and constants[name]!=key:
            # Old sound subtitles can share a spelling with the namespaced skill translation.
            if '.epicfight.' in key:
                constants[name+'_LEGACY']=constants[name]
            else:
                name += '_LEGACY'
        constants[name]=key
    body='\n'.join('    public static final String '+name+' = '+json.dumps(key)+';' for name,key in sorted(constants.items()))
    (dest/(cls+'.java')).write_text('package dev.war.openfight.generated;\n\n// Generated by scripts/generate_keys.py from upstream resources.\npublic final class '+cls+' {\n    private '+cls+'() {}\n'+body+'\n}\n',encoding='utf-8')
    print(f'{cls}: {len(constants)} constants')
